# Rules engine to tag destinations deterministically to ensure quality recommendations
def assign_editorial_profiles(row):
    dest = row['destination_en'].lower()
    country = row['country_en'].lower()
    region = str(row['region_en']).lower()

    # Default placeholders
    interests = ["culture", "relaxation"]
    lengths = ["2-3 days", "4-5 days"]
    seasons = ["spring", "summer", "autumn", "winter"]
    budget = "medium"
    desc = f"Discover the fascinating atmosphere and scenic landscapes of {row['destination_en']}."

    # Thematic tag assignments based on names/locations
    if any(k in dest or k in region for k in ['islas', 'island', 'ibiza', 'mallorca', 'menorca', 'fuerteventura', 'lanzarote', 'gran canaria', 'tenerife', 'corfu', 'santorini', 'mykonos', 'zakynthos', 'zante', 'sardinia', 'sicily', 'creta', 'rhodes']):
        interests = ["beach", "relaxation", "islands"]
        seasons = ["summer", "spring"]
        budget = "high" if any(k in dest for k in ['mykonos', 'santorini', 'ibiza']) else "medium"
        desc = f"A gorgeous escape featuring sun-kissed coasts, sparkling blue waters, and relaxing sea breezes."
    elif any(k in dest for k in ['madrid', 'barcelona', 'paris', 'berlin', 'vienna', 'prague', 'brussels', 'rome', 'milan', 'lisbon', 'amsterdam', 'munich', 'athens', 'florence', 'venice']):
        interests = ["city break", "culture", "food"]
        lengths = ["2-3 days", "4-5 days"]
        budget = "high"
        desc = f"An iconic city getaway bursting with dynamic culture, rich architectural landmarks, and exceptional dining experiences."
    elif any(k in dest or k in region for k in ['asturias', 'bilbao', 'cantabria', 'pyrenees', 'alps', 'zurich', 'geneva', 'salzburg', 'pula', 'split']):
        interests = ["nature and mountains", "relaxation"]
        lengths = ["4-5 days", "a week or more"]
        seasons = ["spring", "autumn", "summer"]
        budget = "medium"
        desc = f"Surround yourself with dramatic green peaks, refreshing clean air, and pristine wilderness trails."
    elif any(k in dest for k in ['marrakech', 'agadir', 'tlemcen', 'algiers', 'constantine']):
        interests = ["culture", "food"]
        lengths = ["4-5 days", "a week or more"]
        seasons = ["autumn", "winter", "spring"]
        budget = "low"
        desc = f"Delight your senses in vibrant traditional markets, explore historical gems, and taste authentic local cuisine."

    return pd.Series({
        'interests': '|'.join(interests),
        'trip_length': '|'.join(lengths),
        'seasons': '|'.join(seasons),
        'budget_tier': budget,
        'description': desc
    })

profile_cols = df.apply(assign_editorial_profiles, axis=1)
df = pd.concat([df, profile_cols], axis=1)

